# Builds ClassAuras.lua: for each class, every spell ID (all ranks) of the debuffs that class puts on enemies.
# OmaDoomed's team row (sheet 104) gives each class its own aura group filtered to these IDs, so a square's line tells
# you which class put it there without reading the caster (hidden in combat on Forever).
# Source of the IDs: Guidelime's SpellDB.lua (name -> every rank's ID). Run again after adding names:
#   python tools/make_class_auras.py "<WoW>/_forever_/Interface/AddOns/Guidelime/Data/SpellDB.lua" > ClassAuras.lua
import re, sys

CLASSES = [  # order = the line order under the target frame
  ('WARRIOR', ['Sunder Armor', 'Rend', 'Demoralizing Shout', 'Thunder Clap', 'Hamstring', 'Mortal Strike',
               'Piercing Howl', 'Disarm', 'Concussion Blow', 'Deep Wound', 'Mocking Blow', 'Intimidating Shout',
               'Charge Stun', 'Intercept Stun', 'Revenge Stun', 'Mace Stun Effect', 'Shield Bash - Silenced']),
  ('ROGUE', ['Garrote', 'Rupture', 'Expose Armor', 'Crippling Poison', 'Deadly Poison', 'Mind-numbing Poison',
             'Wound Poison', 'Kidney Shot', 'Cheap Shot', 'Gouge', 'Blind', 'Sap', 'Hemorrhage', 'Kick - Silenced',
             'Riposte']),
  ('HUNTER', ["Hunter's Mark", 'Serpent Sting', 'Viper Sting', 'Scorpid Sting', 'Wyvern Sting', 'Concussive Shot',
              'Wing Clip', 'Improved Wing Clip', 'Scatter Shot', 'Freezing Trap Effect', 'Immolation Trap Effect',
              'Explosive Trap Effect', 'Frost Trap Aura', 'Counterattack', 'Entrapment', 'Intimidation',
              'Improved Concussive Shot']),
  ('MAGE', ['Frostbolt', 'Chilled', 'Frost Nova', 'Cone of Cold', 'Polymorph', 'Fireball', 'Pyroblast', 'Ignite',
            'Fire Vulnerability', "Winter's Chill", 'Blast Wave', 'Flamestrike', 'Counterspell - Silenced',
            'Frostbite', 'Impact']),
  ('WARLOCK', ['Corruption', 'Curse of Agony', 'Curse of Doom', 'Curse of the Elements', 'Curse of Shadow',
               'Curse of Recklessness', 'Curse of Weakness', 'Curse of Tongues', 'Curse of Exhaustion', 'Immolate',
               'Siphon Life', 'Fear', 'Howl of Terror', 'Death Coil', 'Banish', 'Seduction', 'Spell Lock',
               'Drain Life', 'Drain Soul', 'Drain Mana', 'Bane of Agony', 'Bane of Doom', 'Shadowburn']),
  ('PRIEST', ['Shadow Word: Pain', 'Mind Flay', 'Devouring Plague', 'Holy Fire', 'Vampiric Embrace', 'Psychic Scream',
              'Mind Soothe', 'Shackle Undead', 'Silence', 'Blackout', 'Hex of Weakness', 'Shadow Vulnerability']),
  ('DRUID', ['Faerie Fire', 'Faerie Fire (Feral)', 'Moonfire', 'Insect Swarm', 'Rake', 'Rip', 'Pounce Bleed', 'Pounce',
             'Bash', 'Entangling Roots', 'Hibernate', 'Demoralizing Roar', 'Feral Charge Effect', 'Challenging Roar']),
  ('PALADIN', ['Judgement of Light', 'Judgement of Wisdom', 'Judgement of the Crusader', 'Judgement of Justice',
               'Hammer of Justice', 'Repentance', 'Turn Undead']),
  ('SHAMAN', ['Flame Shock', 'Frost Shock', 'Earth Shock', 'Stormstrike', 'Earthbind']),
]

src = open(sys.argv[1], encoding='utf-8', errors='replace', newline='').read().replace('\r\n', '\n')
# each spell is its own block at one indent level (two tabs): ["KEY"] = { ... },  -- read block by block
entries = {}
for blk in re.split(r'\n\t\t\["[^"]+"\] = \{', src)[1:]:
    blk = blk.split('\n\t\t},')[0]
    nm = re.search(r'\["name"\]\s*=\s*"([^"]+)"', blk)
    idb = re.search(r'\["id"\]\s*=\s*\{([^}]*)\}', blk)
    if nm and idb:
        entries.setdefault(nm.group(1), []).extend(int(x) for x in re.findall(r'(\d+),\s*--', idb.group(1)))
seen, missing, out = {}, [], []
out.append('-- Generated by tools/make_class_auras.py from Guidelime\'s spell database. Do not edit by hand.')
out.append('-- Each class: every rank\'s spell ID of the debuffs it puts on enemies (sheet 104, the team row).')
out.append('local _, ns = ...')
out.append('ns.CLASS_AURAS = {')
for cls, names in CLASSES:
    ids = []
    for n in names:
        got = entries.get(n)
        if not got: missing.append(f'{cls}: {n}'); continue
        for i in got:
            if i in seen: continue          # first class to claim an ID keeps it
            seen[i] = cls; ids.append(i)
    out.append(f'  {{ class = \'{cls}\', ids = {{ {", ".join(str(i) for i in sorted(ids))} }} }},')
out.append('}')
print('\n'.join(out))
sys.stderr.write('missing names (not in the source; Forever-only spells fall to the last line): ' + ', '.join(missing) + '\n')
